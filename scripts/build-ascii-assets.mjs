import { readFile, writeFile } from 'node:fs/promises';
import { asciiSkeletonHTML, SKELETON_CSS } from '../export/vendor/ascii-reveal/core.js';

// Pre-render the upstream skeletons so waiting for the animation engine never
// leaves a blank frame. This asset contains no React or third-party requests.
const templates = {
  posters: JSON.parse(await readFile(new URL('../export/ascii-posters.json', import.meta.url), 'utf8')),
  css: SKELETON_CSS,
  media: asciiSkeletonHTML({ variant: 'scan', rows: 20, seed: 17, css: false, animate: true }),
  avatar: asciiSkeletonHTML({ variant: 'braille', rows: 12, seed: 31, css: false, animate: true }),
};
await writeFile(new URL('../export/ascii-skeletons.js', import.meta.url),
  '/* Generated by scripts/build-ascii-assets.mjs using ascii-reveal 0.3.0. */\n' +
  'window.__brAsciiSkeletons = ' + JSON.stringify(templates) + ';\n');
console.log('Built local ASCII skeleton templates.');
